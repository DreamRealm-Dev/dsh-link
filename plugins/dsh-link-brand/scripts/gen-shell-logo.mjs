#!/usr/bin/env node
/**
 * Render the brand artwork in `assets/` into the shell's boot page.
 *
 *   node plugins/dsh-link-brand/scripts/gen-shell-logo.mjs
 *
 * The shell's boot page is a single self-contained document served before the
 * kernel exists, so it cannot fetch a logo: the artwork is inlined at compile
 * time as Rust constants. Two rewrites, the same ones the client half uses:
 * the ink becomes `currentColor` (the page's own `--boot-label-primary` token
 * then drives it in both palettes, while the ring keeps the design's blue), and
 * the mask ids are fixed, because the artwork's mask cannot be shared with the
 * client document and the boot page renders each mark exactly once.
 *
 * The generated file is committed, so the Rust build needs no Node step.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..', '..', '..')
const ASSETS = join(HERE, '..', 'assets')
const OUTPUT = join(ROOT, 'src-tauri', 'src', 'core', 'brand_art.rs')

const INK = /fill="#0F1115"/g

/** Read one asset and return its markup with the boot page's class and a stable mask id. */
function inline(file, className, maskId, viewBoxOverride) {
  let text = readFileSync(join(ASSETS, file), 'utf8')
    .replace(/\r\n?/g, '\n')
    .replace(/^<\?xml[^>]*>\s*/m, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/m, '')
    .replace(INK, 'fill="currentColor"')
  // One instance per document: the artwork's own mask id would collide with the
  // client document's when both are open, and reusing it here keeps the markup readable.
  text = text.replace(/id="cut"/g, 'id="' + maskId + '"').replace(/url\(#cut\)/g, 'url(#' + maskId + ')')
  const viewBox = viewBoxOverride ?? /viewBox="([^"]+)"/.exec(readFileSync(join(ASSETS, file), 'utf8'))[1]
  // One line: the constant is a single HTML fragment, and the indentation the SVG
  // carried is not meaningful in the served document.
  return '<svg class="' + className + '" viewBox="' + viewBox + '" fill="none" aria-hidden="true">'
    + text.replace(/^\s+/gm, '').replace(/\s*\n\s*/g, ' ').replace(/\s{2,}/g, ' ').trim()
    + '</svg>'
}

// The wordmark alone: it already carries the symbol inside its 'd', so the mark next
// to it would set LINK twice. The square surfaces (rail, hero, app icon) use the
// badge, which the client half draws from the same design.
const wordmark = inline('dsh-link-in-d.svg', 'brand-wordmark', 'dsh-link-boot-wordmark')

const file = `//! Generated by plugins/dsh-link-brand/scripts/gen-shell-logo.mjs from
//! plugins/dsh-link-brand/assets/ — edit the SVG there, then rerun the script.
//!
//! The shell's boot page cannot fetch anything (it is served before the kernel
//! that would serve an asset exists), so its brand artwork is inlined at compile
//! time. Ink is \`currentColor\` so the page's own palette token drives it.

/// The DSH Link wordmark. Sized by the boot page's stylesheet.
pub const WORDMARK_SVG: &str = r##"${wordmark}"##;
`

const before = (() => { try { return readFileSync(OUTPUT, 'utf8') } catch { return undefined } })()
if (before === file) {
  console.log('ok: src-tauri/src/core/brand_art.rs (' + file.length + ' bytes, unchanged)')
} else {
  writeFileSync(OUTPUT, file)
  console.log((before === undefined ? 'wrote   ' : 'updated ') + 'src-tauri/src/core/brand_art.rs  ' + file.length + ' bytes')
}
