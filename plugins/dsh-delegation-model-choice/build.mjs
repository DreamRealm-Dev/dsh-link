/**
 * Build the dynamic Cordis host body from the canonical package source.
 *
 * `lib/index.js` is the single source of truth. The dynamic Cordis evaluator runs
 * a plain JavaScript function body with no imports, so this script extracts the
 * marked core and appends a small dynamic footer that wires `harness` in.
 *
 * Usage: node build.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const START = '// ---8<--- CORE START ---8<---'
const END = '// ---8<--- CORE END ---8<---'

const source = readFileSync(join(root, 'lib', 'index.js'), 'utf8')
const start = source.indexOf(START)
const end = source.indexOf(END)
if (start < 0 || end < 0) throw new Error('core markers missing from lib/index.js')
const core = source.slice(start + START.length, end)

const dynamic = `// GENERATED by build.mjs from lib/index.js — do not edit by hand.
// Dynamic Cordis host body: plain JavaScript, no imports, no Node globals.
const core = (function () {
${core}
return { resolveConfig, installScope }
})()

/**
 * Sandbox-only approval adapter. The dynamic evaluator runs in its own VM realm,
 * so a request object built here fails the api gateway's lossless-JSON check
 * (its object prototypes are the VM's, not the host's). Rebuild the question
 * payload out of host-realm containers instead: a fresh host array from
 * ctx.subagents.list() and host objects from ctx.tools.schemas(). A real Cordis
 * plugin runs in the host realm and needs none of this.
 */
function sandboxHostRequest(ctx, request) {
  const scratch = ctx.get('subagents').list()
  const pool = ctx.get('tools').schemas()
  scratch.length = 0
  let index = 0
  for (const question of request.questions) {
    const item = pool[index]
    if (item === undefined) break
    index += 1
    for (const key of Object.keys(item)) delete item[key]
    item.id = String(question.id)
    item.question = String(question.question)
    if (question.header !== undefined) item.header = String(question.header)
    if (question.detail !== undefined) item.detail = String(question.detail)
    if (Array.isArray(question.options) && question.options.length > 0) {
      const options = pool.slice(index, index + question.options.length)
      index += question.options.length
      for (let position = 0; position < options.length; position += 1) {
        const option = options[position]
        const source = question.options[position]
        for (const key of Object.keys(option)) delete option[key]
        option.label = String(source.label)
        if (source.description !== undefined) option.description = String(source.description)
      }
      item.options = options
    }
    scratch.push(item)
  }
  return { questions: scratch, agent: request.agent, signal: request.signal }
}

return {
  name: 'delegation-model-choice',
  inject: ['tools'],
  apply(ctx, config) {
    const helpers = {
      define: (options) => harness.defineTool(options),
      register: (scope, tool) => harness.registerTool(scope, tool),
      hostRequest: (request) => sandboxHostRequest(ctx, request),
    }
    core.installScope(ctx, ctx, core.resolveConfig(config === undefined ? {} : config), helpers)
  },
}
`

writeFileSync(join(root, 'dyn-host.js'), dynamic)

// Compile the dynamic body so a syntax error never reaches the runtime. The
// package entry is checked separately (`node --check` on an .mjs copy) because
// its bare import only resolves inside a DSH profile.
new Function(dynamic)
console.log('ok: dyn-host.js compiled')
console.log('dynamic body bytes:', Buffer.byteLength(dynamic))
